"""Generate engine/verb_lexicon.py from the Brown corpus (run once; needs `brown` NLTK data)."""
import collections, os, sys
sys.path.insert(0, os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
from engine.nltk_setup import ensure, TRAINING
ensure(TRAINING)
from nltk.corpus import brown

base, vbd, vbn = collections.Counter(), collections.Counter(), collections.Counter()
for w, t in brown.tagged_words():
    w = w.lower()
    if not w.isalpha() or len(w) < 2:
        continue
    t = t.split("-")[0].split("+")[0]
    if t in ("VB", "BE", "DO", "HV"):
        base[w] += 1
    elif t == "VBD":
        vbd[w] += 1
    elif t == "VBN":
        vbn[w] += 1
verbs = sorted(w for w, c in base.items() if c >= 2)
irregular_past = {}
with open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "engine", "verb_lexicon.py"), "w") as f:
    f.write('"""AUTO-GENERATED by tools/make_verb_lexicon.py from the Brown corpus. Do not edit."""\n')
    f.write("VERBS = frozenset(%r)\n" % (verbs,))
print(len(verbs), "verbs")
